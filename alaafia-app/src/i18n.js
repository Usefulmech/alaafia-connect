function getLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) || 'English';
    if (saved === 'Yorùbá') return 'yo';
    if (saved === 'Hausa') return 'ha';
    if (saved === 'Igbo') return 'ig';
    if (saved === 'Pidgin') return 'pidgin';
    return 'en';
  } catch { return 'en'; }
}

export function useT() {
  const [lang, setLang] = useState(getLang());

  useEffect(() => {
    const handler = () => setLang(getLang());
    window.addEventListener('language-changed', handler);
    window.addEventListener('storage', handler);
    return () => {
      window.removeEventListener('language-changed', handler);
      window.removeEventListener('storage', handler);
    };
  }, []);

  return function t(key, fallback) {
    const dict = TRANSLATIONS[lang] || {};
    if (dict[key]) return dict[key];
    if (fallback) return fallback;
    return key;
  };
}

export function getCurrentLang() {
  return getLang();
}
