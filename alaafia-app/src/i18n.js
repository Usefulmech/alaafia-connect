const STORAGE_KEY = 'selectedLanguage';

const LANG_MAP = {
  English: 'en',
  Yorùbá: 'yo',
  Hausa: 'ha',
  Igbo: 'ig',
  Pidgin: 'pidgin',
};

function getInitialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) || 'English';
    return LANG_MAP[saved] || 'en';
  } catch { return 'en'; }
}

function syncToStorage(lang) {
  try {
    const reverse = { en: 'English', yo: 'Yorùbá', ha: 'Hausa', ig: 'Igbo', pidgin: 'Pidgin' };
    localStorage.setItem(STORAGE_KEY, reverse[lang] || 'English');
  } catch {}
}

